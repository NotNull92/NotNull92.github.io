export function translate(text, language = 'en') {
  if (language !== 'ko' || typeof text !== 'string') return text;
  const value = text.trim();
  let result = Object.hasOwn(translations, value) ? translations[value] : undefined;
  if (result === undefined) {
    let match;
    if ((match = value.match(/^Talk to (.+)$/))) result = translate(match[1], language) + '와 이야기하기';
    else if ((match = value.match(/^Open (.+) project record$/))) result = translate(match[1], language) + ' 프로젝트 기록 열기';
    else if ((match = value.match(/^PROJECT (\d+)$/))) result = '프로젝트 ' + match[1];
    else if ((match = value.match(/^Ember Studio Archive · Project (\d+)$/))) result = '엠버 스튜디오 기록실 · 프로젝트 ' + match[1];
    else if ((match = value.match(/^Pages? (\d+(?:–\d+)?) of (\d+)$/))) result = '전체 ' + match[2] + '쪽 중 ' + match[1] + '쪽';
    else if ((match = value.match(/^Page (\d+): (.+)$/))) result = match[1] + '쪽: ' + translate(match[2], language);
    else if ((match = value.match(/^(\d+) \/ (.+)$/))) result = match[1] + ' / ' + translate(match[2], language);
    else if ((match = value.match(/^EMBER STUDIO \/ (\d+)$/))) result = '엠버 스튜디오 / ' + match[1];
    else if ((match = value.match(/^(.+) — Ember Studio$/))) result = translate(match[1], language) + ' — 엠버 스튜디오';
    else if ((match = value.match(/^(Julie|Mora|Bara|Star|Jenny|Pixie), (.+)$/))) result = translate(match[1], language) + ', ' + translate(match[2], language);
    else if ((match = value.match(/^([←↗]\s*)(.+)$/))) result = match[1] + translate(match[2], language);
    else if ((match = value.match(/^(.+?)(\s*[→↗])$/))) result = translate(match[1], language) + match[2];
  }
  return result === undefined ? text : text.replace(value, () => result);
}
